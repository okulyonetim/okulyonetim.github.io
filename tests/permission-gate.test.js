const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync('js/core/permission-gate.js','utf8');
const listeners={};
const win={addEventListener:(n,f)=>{listeners[n]=f},localStorage:{getItem(){return null},setItem(){},removeItem(){}}};
win.window=win;
vm.runInNewContext(src,{window:win,localStorage:win.localStorage,document:{},navigator:{},console,Date,JSON,Promise,Math,Number,setTimeout});
const G=win.KorukPermissionGate,D=86400000,n=Date.now();
assert(G&&typeof G.due==='function','KorukPermissionGate.due olmalı.');
assert.deepStrictEqual([...G.WAIT_DAYS],[0,1,3,7],'Bekleme günleri 0,1,3,7 olmalı.');
assert.strictEqual(G.due({}),true,'İlk açılışta gösterilmeli.');
assert.strictEqual(G.due({n:1,ts:n-D/2}),false,'1. gösterimden sonra 1 gün beklenmeli.');
assert.strictEqual(G.due({n:1,ts:n-D-1}),true);
assert.strictEqual(G.due({n:2,ts:n-2*D}),false,'2. gösterimden sonra 3 gün beklenmeli.');
assert.strictEqual(G.due({n:2,ts:n-3*D-1}),true);
assert.strictEqual(G.due({n:9,ts:n-6*D}),false,'Sonraki gösterimlerde en çok 7 gün.');
assert.strictEqual(G.due({n:9,ts:n-7*D-1}),true);
assert(typeof listeners['koruk:app-ready']==='function','Giriş sonrası (koruk:app-ready) dinlenmeli.');
for(const f of ['index.html','beta.html'])assert(fs.readFileSync(f,'utf8').includes('js/core/permission-gate.js'),f+' izin sayfası betiğini yüklemeli.');
assert(fs.readFileSync('service-worker.js','utf8').includes('permission-gate.js'),'Servis çalışanı betiği önbelleğe almalı.');
assert(/PushService\??\.?tokenGetir|tokenGetir\(\{request:true\}\)/.test(src)&&/refreshWeather/.test(src),'Mevcut bildirim kaydı ve hava durumu yenileme kullanılmalı.');
console.log('permission-gate: OK');
