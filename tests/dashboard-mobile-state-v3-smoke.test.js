assert(!js.includes('setInterval('),'Yeni durum yöneticisi sürekli polling kullanmamalı.');
assert(ui.includes("dashboard-mobile-state-v3.js"),'Durum yöneticisi mobil yükleme zincirinde olmalı.');
assert(sw.includes("'./js/dashboard-mobile-state-v3.js'"),'Durum yöneticisi PWA precache içinde olmalı.');
